import React, { useCallback, useEffect, useMemo, useRef, useState } from 'react'
import {
  CartesianGrid, Legend, Line, LineChart, ReferenceLine, ResponsiveContainer, Tooltip, XAxis, YAxis,
} from 'recharts'
import { api } from './api.js'

const REFRESH_MS = 2000

const STATE_TEXT = {
  NORMAL_FLOW: 'Normal flow',
  FLOW_INTERRUPTION: 'Flow interruption',
  HIGH_MASS_LOSS_RATE: 'High mass-loss rate (possible free flow, unvalidated)',
  BAG_REPLACEMENT: 'Bag replacement',
  LOW_VOLUME: 'Low volume',
  SENSOR_UNCERTAIN: 'Sensor data uncertain',
  SENSOR_NORMAL: 'Sensor normal',
  POSSIBLE_DRIFT: 'Possible drift',
  POSSIBLE_STUCK_SIGNAL: 'Possible stuck signal',
  ABNORMAL_NOISE: 'Abnormal noise',
}
const STATE_TONE = {
  NORMAL_FLOW: 'good', SENSOR_NORMAL: 'good', BAG_REPLACEMENT: 'info',
  FLOW_INTERRUPTION: 'bad', HIGH_MASS_LOSS_RATE: 'bad', LOW_VOLUME: 'warn',
  SENSOR_UNCERTAIN: 'warn', POSSIBLE_DRIFT: 'warn', POSSIBLE_STUCK_SIGNAL: 'warn', ABNORMAL_NOISE: 'warn',
}
const LABEL_TONE = { LIVE: 'good', SIMULATED: 'sim', STALE: 'warn', UNAVAILABLE: 'bad', HISTORICAL: 'muted' }
const LABEL_HELP = {
  LIVE: 'Fresh readings from the real device',
  SIMULATED: 'Generated by the simulator. Not a physical measurement.',
  STALE: 'No fresh data: the device is offline or readings stopped',
  UNAVAILABLE: 'No data could be read',
  HISTORICAL: 'Viewing stored data from a source that is not running now',
}
const GT_KINDS = [
  'NORMAL_FLOW', 'FLOW_INTERRUPTION', 'HIGH_MASS_LOSS_RATE', 'BAG_REPLACEMENT', 'LOW_VOLUME',
  'SENSOR_UNCERTAIN', 'POSSIBLE_DRIFT', 'POSSIBLE_STUCK_SIGNAL', 'ABNORMAL_NOISE', 'CALIBRATION', 'STATIONARY_LOAD',
]

const PRIORITY_TONE = { high: 'bad', medium: 'warn', low: 'info', info: 'muted' }

const fmt = (v, d = 1) => (v === null || v === undefined || Number.isNaN(v) ? '—' : Number(v).toFixed(d))
const time = (iso) => (iso ? new Date(iso).toLocaleTimeString() : '—')
const dateTime = (iso) => (iso ? new Date(iso).toLocaleString() : '—')
const stateText = (s) => STATE_TEXT[s] || s || '—'

function Badge({ tone, children, title }) {
  return <span className={`badge ${tone || 'muted'}`} title={title}>{children}</span>
}

function Tile({ label, value, unit, sub, tone }) {
  return (
    <div className={`tile ${tone || ''}`}>
      <div className="tile-label">{label}</div>
      <div className="tile-value">{value}{unit && <span className="unit"> {unit}</span>}</div>
      {sub && <div className="tile-sub">{sub}</div>}
    </div>
  )
}

function Panel({ title, children, right }) {
  return (
    <section className="panel">
      <div className="panel-head"><h2>{title}</h2>{right}</div>
      {children}
    </section>
  )
}

function useSource() {
  const [source, setSource] = useState(null)
  return [source, setSource]
}

